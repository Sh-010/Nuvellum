// Regenerates src/lib/world-map-data.js (World Desk map) from Natural Earth 1:50m admin-0
// countries (public domain, via the world-atlas package).
//
//   npm i --no-save d3-geo@3 topojson-client@3 topojson-simplify@3 world-atlas@2
//   node scripts/tools/generate-world-map.mjs
//
// Projection: equirectangular (plate carrée), clipped to 58°S–84°N so every inhabited landmass
// (Arctic Canada/Greenland to Tierra del Fuego) is kept and only Antarctica is left out.
// Country-to-desk grouping is taken from the current data file by country name; territories
// that exist only at 1:50m inherit the desk of the nearest already-grouped country.
import { writeFileSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { geoEquirectangular, geoPath, geoCentroid, geoDistance } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, simplify, sphericalTriangleArea } from 'topojson-simplify';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outFile = join(root, 'src', 'lib', 'world-map-data.js');

export const VIEW_WIDTH = 1000;
export const NORTH = 84;
export const SOUTH = -58;
const VIEW_HEIGHT = Math.round(VIEW_WIDTH * (NORTH - SOUTH) / 360 * 10) / 10;

// Existing grouping (name -> desk).
const { WORLD_MAP_GROUPS: current } = await import(new URL(`file://${outFile.replace(/\\/g, '/')}`).href + `?t=${Date.now()}`);
const deskOf = new Map();
for (const [desk, countries] of Object.entries(current)) for (const c of countries) deskOf.set(c.name, desk);

const topo50 = require('world-atlas/countries-50m.json');
const simplified = simplify(presimplify(topo50, sphericalTriangleArea), Number(process.env.MIN_WEIGHT || 2e-7));
const countries = feature(simplified, simplified.objects.countries).features;

// Centroids of already-grouped countries (from the 50m shapes of the same names).
const anchors = countries.filter(f => deskOf.has(f.properties.name)).map(f => ({ desk: deskOf.get(f.properties.name), c: geoCentroid(f) }));
const excluded = new Set(['Antarctica', 'Fr. S. Antarctic Lands', 'Heard I. and McDonald Is.']);
// Nearest-neighbour exceptions where proximity picks the wrong desk.
const OVERRIDES = { Malta: 'europe-central-asia', 'Siachen Glacier': 'south-asia', Bermuda: 'north-america' };

const projection = geoEquirectangular()
  .scale(VIEW_WIDTH / (2 * Math.PI))
  .translate([VIEW_WIDTH / 2, (NORTH / 180) * Math.PI * (VIEW_WIDTH / (2 * Math.PI))])
  .clipExtent([[0, 0], [VIEW_WIDTH, VIEW_HEIGHT]])
  .precision(0.2);
const path = geoPath(projection).digits(1);

const groups = Object.fromEntries(Object.keys(current).map(k => [k, []]));
const inherited = [];
const dropped = [];
for (const f of countries) {
  const name = f.properties.name;
  if (excluded.has(name)) continue;
  let desk = OVERRIDES[name] || deskOf.get(name);
  if (!desk) {
    const c = geoCentroid(f);
    desk = anchors.reduce((best, a) => (geoDistance(c, a.c) < best.d ? { d: geoDistance(c, a.c), desk: a.desk } : best), { d: Infinity }).desk;
    inherited.push(`${name} -> ${desk}`);
  }
  // Territories that simplification reduces to zero drawable area (sub-pixel specks) are skipped.
  const d = path(f);
  if (d && path.area(f) >= 0.02) groups[desk].push({ name, d }); else dropped.push(name);
}

const body = `// Generated by scripts/tools/generate-world-map.mjs from Natural Earth 1:50m admin-0 country data (public domain).
// Projection: equirectangular, ${Math.abs(SOUTH)}°S–${NORTH}°N (Antarctica omitted); viewBox 0 0 ${VIEW_WIDTH} ${VIEW_HEIGHT}. Source: https://github.com/nvkelso/natural-earth-vector
export const WORLD_MAP_VIEWBOX = '0 0 ${VIEW_WIDTH} ${VIEW_HEIGHT}';
export const WORLD_MAP_GROUPS = ${JSON.stringify(groups)};
`;
writeFileSync(outFile, body);
const total = Object.values(groups).reduce((n, g) => n + g.length, 0);
console.log(`wrote ${outFile}: ${total} countries, ${(body.length / 1024).toFixed(0)} KB`);
if (dropped.length) console.log('skipped (no drawable area at this scale): ' + dropped.join(', '));
if (inherited.length) console.log('desk inherited from nearest neighbour:\n  ' + inherited.join('\n  '));
