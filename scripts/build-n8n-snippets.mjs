// Generates n8n/snippets/*.js from the tested repository libraries so the
// code pasted into n8n Code nodes is byte-for-byte the code CI tests.
// Run: npm run n8n:snippets   (CI fails if the committed snippets are stale)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './lib/paths.mjs';

const strip = (file) => readFileSync(join(root, 'scripts', 'lib', file), 'utf8')
  .replace(/^import .*$/gm, '')
  .replace(/^export (const|function|let|class)/gm, '$1');

const LIBS = { newsroom: strip('newsroom.mjs'), svg: strip('svg-safety.mjs') };

const header = (name, purpose, libs) => `// ${name} — GENERATED by scripts/build-n8n-snippets.mjs. Do not edit in n8n;
// edit scripts/lib/*.mjs in the repository, run \`npm run n8n:snippets\`, and paste.
// n8n Code node: mode "Run Once for All Items", language JavaScript.
// Purpose: ${purpose}
/* eslint-disable */
${libs.map(l => LIBS[l]).join('\n')}
// ---- node body -------------------------------------------------------------
`;

const SNIPPETS = {
  'normalize-candidates.js': {
    purpose: 'Canonicalize RSS candidates, drop items without URLs or from live blogs/video pages, dedupe within the run, and attach the deterministic source hash.',
    libs: ['newsroom'],
    body: `const seen = new Set();
const out = [];
for (const item of $input.all()) {
  const j = item.json || {};
  const raw = j.link || j.url || j.guid || '';
  let canonical;
  try { canonical = canonicalSourceUrl(raw); } catch { continue; }          // no/invalid URL -> skip
  if (isAggregatePage(canonical)) continue;                                 // live blog / video / gallery
  if (seen.has(canonical)) continue;                                        // duplicate in this run
  seen.add(canonical);
  out.push({ json: { ...j, canonicalUrl: canonical, sourceHash: sha256Hex(canonical).slice(0, 8) } });
}
return out;`
  },
  'parse-review.js': {
    purpose: 'Turn the editorial reviewer model output (json.reviewText) into {editorialReview, risk, problems}. Fails closed.',
    libs: ['newsroom'],
    body: `return $input.all().map(item => ({ json: { ...item.json, review: parseEditorialReview(item.json.reviewText ?? item.json.text ?? '') } }));`
  },
  'parse-verification.js': {
    purpose: 'Turn the sensitive verifier output (json.verificationText) into {verification, problems}. Fails closed.',
    libs: ['newsroom'],
    body: `return $input.all().map(item => ({ json: { ...item.json, verification: parseVerification(item.json.verificationText ?? item.json.text ?? '') } }));`
  },
  'validate-svg.js': {
    purpose: 'Validate the generated SVG (json.svg). On any problem, drop the art (aiArt=false) so the section image is used.',
    libs: ['svg'],
    body: `return $input.all().map(item => {
  const svg = String(item.json.svg || '');
  const problems = svg ? validateSvg(svg, 'editorial-svg') : ['no svg'];
  return { json: { ...item.json, aiArt: problems.length === 0, svg: problems.length ? '' : svg, svgProblems: problems } };
});`
  },
  'build-article.js': {
    purpose: 'Build the article Markdown, path, art path and deterministic branch. Status is derived from review/verification, never set by hand.',
    libs: ['newsroom'],
    body: `return $input.all().map(item => ({ json: { ...item.json, article: buildArticle(item.json) } }));`
  }
};

const outDir = join(root, 'n8n', 'snippets');
mkdirSync(outDir, { recursive: true });
const check = process.argv.includes('--check');
let stale = [];
for (const [file, s] of Object.entries(SNIPPETS)) {
  const content = header(file, s.purpose, s.libs) + s.body + '\n';
  const path = join(outDir, file);
  if (check) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch {}
    if (current !== content) stale.push(file);
  } else {
    writeFileSync(path, content);
  }
}
if (check && stale.length) {
  console.error(`n8n snippets are stale: ${stale.join(', ')}. Run npm run n8n:snippets.`);
  process.exit(1);
}
console.log(check ? 'n8n snippets are up to date.' : `Wrote ${Object.keys(SNIPPETS).length} n8n snippets.`);
